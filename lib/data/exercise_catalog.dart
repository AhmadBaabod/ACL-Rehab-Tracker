  static Exercise? byId(String id) {
    for (final exercise in all) {
      if (exercise.id == id) return exercise;
    }
    return null;
  }

  static List<Exercise> forPhase(RehabPhase phase) {
    return all.where((exercise) => exercise.phase == phase).toList();
  }

  static List<Exercise> sessionFor(
    Assessment assessment, {
    required MilestoneCheckIn? milestone,
    required RehabPhase phase,
  }) {
    final selectedBlocks = <SessionBlock>{};
    final plan = <Exercise>[];

    for (final exercise in forPhase(phase)) {
      if (!exercise.unlockStatus(assessment, milestone).isUnlocked ||
          !selectedBlocks.add(exercise.sessionBlock)) {
        continue;
      }
      plan.add(exercise);
    }

    return plan;
  }

  static List<Exercise> alternativesFor(
    Exercise exercise,
    Assessment assessment, {
    required MilestoneCheckIn? milestone,
  }) {
    return exercise.alternativeExerciseIds
        .map(byId)
        .whereType<Exercise>()
        .where(
          (alternative) =>
              alternative.phase == exercise.phase &&
              alternative.sessionBlock == exercise.sessionBlock &&
              alternative.unlockStatus(assessment, milestone).isUnlocked,
        )
        .toList();
  }

  static List<Exercise> unlockedFor(
    Assessment assessment, {
    required MilestoneCheckIn? milestone,
  }) {
    return all
        .where(
          (exercise) => exercise.unlockStatus(assessment, milestone).isUnlocked,
        )
        .toList();
  }
