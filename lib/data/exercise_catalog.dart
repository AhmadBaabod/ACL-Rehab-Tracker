  static Exercise _exercise({
    required String id,
    required String name,
    required String description,
    required List<String> instructions,
    required List<String> targets,
    required List<String> equipment,
    required int sets,
    required String reps,
    required String holdTime,
    required String regression,
    required String progression,
    required DifficultyLevel difficulty,
    required ExerciseCriteria criteria,
    required RehabPhase phase,
    required ExerciseCategory category,
    required SessionBlock sessionBlock,
    required String medicalNotes,
    required List<String> safety,
    required List<String> alternatives,
  }) {
    return Exercise(
      id: id,
      name: name,
      description: description,
      instructions: instructions,
      targetMuscles: targets,
      equipment: equipment,
      imagePlaceholder: '$name movement guide',
      videoPlaceholder: 'Clinician-approved video when available',
      sets: sets,
      reps: reps,
      holdTime: holdTime,
      regression: regression,
      progression: progression,
      difficultyLevel: difficulty,
      criteriaRequired: criteria,
      phase: phase,
      category: category,
      sessionBlock: sessionBlock,
      medicalNotes: medicalNotes,
      safetyWarnings: safety,
      alternativeExerciseIds: alternatives,
    );
  }

  static Exercise? byId(String id) {
    for (final exercise in all) {
      if (exercise.id == id) return exercise;
    }
    return null;
  }

  static List<Exercise> forPhase(RehabPhase phase) {
    return all.where((exercise) => exercise.phase == phase).toList();
  }

  static List<Exercise> sessionFor(
    Assessment assessment, {
    required MilestoneCheckIn? milestone,
    required RehabPhase phase,
  }) {
    final selectedBlocks = <SessionBlock>{};
    final plan = <Exercise>[];

    for (final exercise in forPhase(phase)) {
      if (!exercise.unlockStatus(assessment, milestone).isUnlocked ||
          !selectedBlocks.add(exercise.sessionBlock)) {
        continue;
      }
      plan.add(exercise);
    }

    return plan;
  }

  static List<Exercise> alternativesFor(
    Exercise exercise,
    Assessment assessment, {
    required MilestoneCheckIn? milestone,
  }) {
    return exercise.alternativeExerciseIds
        .map(byId)
        .whereType<Exercise>()
        .where(
          (alternative) =>
              alternative.phase == exercise.phase &&
              alternative.sessionBlock == exercise.sessionBlock &&
              alternative.unlockStatus(assessment, milestone).isUnlocked,
        )
        .toList();
  }

  static List<Exercise> unlockedFor(
    Assessment assessment, {
    required MilestoneCheckIn? milestone,
  }) {
    return all
        .where(
          (exercise) => exercise.unlockStatus(assessment, milestone).isUnlocked,
        )
        .toList();
  }
